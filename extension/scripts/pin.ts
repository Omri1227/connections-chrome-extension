// Version / contract pin of what the extension bundles (R-01). The extension bundles the airport models and the shared
// router from THIS tree (airportmaps/data, airportmaps/src) and imports the flight-data contract types from
// flightdata/src/lookup.ts. The pin records content hashes of those inputs in extension/src/core/bundle-info.ts:
//   npx tsx extension/scripts/pin.ts   regenerate the pin after merging maps / flight-data changes
// tests/extension.pin.test.ts and the extension build fail when an input changed without the pin being updated.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const ROOT = path.join(import.meta.dirname, '..', '..');
export const PIN_FILE = path.join(ROOT, 'extension', 'src', 'core', 'bundle-info.ts');
/** Router / schema files the extension executes (the single shared router). */
export const ENGINE_FILES = ['airportmaps/src/route.ts', 'airportmaps/src/types.ts'];
const CONTRACT_FILE = 'flightdata/src/lookup.ts';
const CONTRACT_TYPES = ['FieldAnswer', 'FlightAnswer', 'ConnectionAnswer'];

const read = (rel: string) => fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
const sha = (s: string) => crypto.createHash('sha256').update(s).digest('hex');

/** Airport models of the maps layer that the extension does NOT bundle (kept in the repo for history). IST was replaced
 *  by LHR on 2026-11-02 (owner decision). */
export const INACTIVE_MODELS = ['ist'];

export function modelFiles(): string[] {
  const dir = path.join(ROOT, 'airportmaps', 'data');
  return fs.readdirSync(dir).filter((d) => fs.existsSync(path.join(dir, d, 'airport.json')) && !INACTIVE_MODELS.includes(d)).sort().map((d) => `airportmaps/data/${d}/airport.json`);
}

/** The exported contract interfaces of the flight-data lookup, as text (the SQL may change; the contract may not silently). */
export function contractText(): string {
  const src = read(CONTRACT_FILE);
  return CONTRACT_TYPES.map((t) => {
    const i = src.indexOf(`export interface ${t} {`);
    if (i < 0) throw new Error(`contract type ${t} not found in ${CONTRACT_FILE}`);
    const j = src.indexOf('\n}\n', i);
    return src.slice(i, j + 2);
  }).join('\n');
}

export interface Pin { mapsHash: string; engineHash: string; contractHash: string; files: Record<string, string>; models: Record<string, string> }

export function computePin(): Pin {
  const files: Record<string, string> = {};
  for (const f of [...modelFiles(), ...ENGINE_FILES]) files[f] = sha(read(f)).slice(0, 16);
  const models: Record<string, string> = {};
  for (const f of modelFiles()) models[f.split('/')[2].toUpperCase()] = JSON.parse(read(f)).asOf;
  const mapsHash = sha(Object.entries(files).map(([k, v]) => `${k}:${v}`).join('\n'));
  const engineHash = sha(ENGINE_FILES.map((f) => files[f]).join('\n'));
  return { mapsHash, engineHash, contractHash: sha(contractText()), files, models };
}

export function pinSource(p: Pin): string {
  return `// GENERATED by \`npx tsx extension/scripts/pin.ts\` (extension/scripts/pin.ts). Do not edit by hand.
// Content hashes of the airport models, the shared router and the flight-data contract this extension bundles (R-01).
// tests/extension.pin.test.ts fails when any of them changes without regenerating this file.
export const BUNDLE_INFO = ${JSON.stringify(p, null, 2)} as const;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  fs.writeFileSync(PIN_FILE, pinSource(computePin()));
  console.log(`pin written: ${path.relative(ROOT, PIN_FILE)}`);
}
